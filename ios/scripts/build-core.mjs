import {build} from '../../apps/wechat/node_modules/esbuild/lib/main.js';
import {readFile, writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const root = fileURLToPath(new URL('../../', import.meta.url));
const result = await build({entryPoints: [path.join(root, 'ios/Core/bridge.js')], bundle: true, write: false,
  format: 'iife', globalName: 'XunjuCore', target: 'safari17', platform: 'neutral', mainFields: ['module', 'main'], legalComments: 'none', minifyWhitespace: true, metafile: true});
const sources = {};
for (const input of Object.keys(result.metafile.inputs).sort()) {
  const absolute = path.resolve(input);
  sources[path.relative(root, absolute)] = createHash('sha256').update(await readFile(absolute)).digest('hex');
}
const banner = '// Generated by ios/scripts/build-core.mjs. Do not edit.\n// Sources: ' + JSON.stringify(sources) + '\n';
const text = banner + result.outputFiles[0].text;
const output = path.join(root, 'ios/Xunju/Resources/XunjuCore.js');
if (process.argv.includes('--check')) {
  if (await readFile(output, 'utf8').catch(() => '') !== text) throw Error('Native core is stale. Run node ios/scripts/build-core.mjs');
} else {
  await writeFile(output, text);
}
console.log(`Native core: ${Object.keys(sources).length} canonical sources, ${Buffer.byteLength(text)} bytes`);
